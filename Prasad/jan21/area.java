package Prasad.jan21;

public class area {
    public static void main(String[] args) {
        double radius = 5.0; // Example radius
        double area = Math.PI * radius * radius; // Area = π * r²
        
        System.out.println("Area of Circle with radius " + radius + " is: " + area);
    }
}

